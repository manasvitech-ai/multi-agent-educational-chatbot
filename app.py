def manager_agent(state: ChatState) -> ChatState:
    user_message = state["user_message"]

    prompt = f"""
You are the Manager Agent of a general-purpose AI chatbot.

Classify the user's question into exactly ONE category:

- STUDY: questions about academic subjects, explanations, education or learning
- CODING: programming, Python, Java, algorithms, debugging or technical coding
- GENERAL: everything else, including career, placement, daily life and general questions

User question:
{user_message}

Reply with ONLY one word:
STUDY
CODING
or
GENERAL
"""

    response = llm.invoke(prompt)

    category = response.content.strip().upper()

    if category not in ["STUDY", "CODING", "GENERAL"]:
        category = "GENERAL"

    print(f"🧠 Manager Agent → {category}")

    return {
        **state,
        "response": category
    }

