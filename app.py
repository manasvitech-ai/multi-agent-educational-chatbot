def route_question(question):
    """
    Connects Manager Agent with Study, Coding and General Agents.
    """

    # Create the state expected by the agents
    state = {
        "user_message": question
    }

    # -------------------------
    # STEP 1: Manager Agent
    # -------------------------
    manager_result = manager_agent(state)

    # Manager stores category in "response"
    category = manager_result["response"]

    # -------------------------
    # STEP 2: Route the question
    # -------------------------
    if category == "STUDY":

        result = study_agent(state)
        answer = result["response"]

    elif category == "CODING":

        answer = coding_agent(question)

    else:

        answer = general_agent(question)

    return category, answer


