from typing import TypedDict, List

class ChatState(TypedDict):
    user_message: str
    response: str

print("Chat state created successfully!")

def chat_agent(state: ChatState) -> ChatState:
    user_message = state["user_message"]

    response = llm.invoke(user_message)

    return {
        "user_message": user_message,
        "response": response.content
    }

print("Chat Agent created successfully!")

from langgraph.graph import StateGraph, START, END

# Create the graph
graph_builder = StateGraph(ChatState)

# Add our Chat Agent
graph_builder.add_node("chat_agent", chat_agent)

# Define the flow
graph_builder.add_edge(START, "chat_agent")
graph_builder.add_edge("chat_agent", END)

# Compile the chatbot
chatbot_graph = graph_builder.compile()

